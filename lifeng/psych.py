"""砺锋 v2 —— 心理资源库。

**范围声明（重要）**：本模块只提供**自助调节技巧与求助指引**，
**不做情绪检测、不做心理诊断、不给个体化评估**。

原因：
1. 从文本推断情绪不可靠，误判代价高；
2. 服务对象含未成年人，情绪数据属敏感个人信息；
3. AI 不具备做心理判断的资质。

因此界面上它是「资源页」而不是「检测页」：学生自己判断
"我现在是哪种状态"，然后取用对应的方法。

**内容来源**：原《技术方向文档》的心理资料库部分，并做了三点处理：
- 删去无法核实的内容，保留下来的都是公开、常见、低风险的自助技巧
- **耶克斯-多德森定律**保留但标注了争议（倒 U 型的实证支持较弱）
- **求助热线号码不写死** —— 写错热线比不写更危险，
  改由教师在本机填入当地号码（见 :data:`CRISIS_CONTACT_PLACEHOLDER`）
"""

from __future__ import annotations

from dataclasses import dataclass, field

#: 求助联系方式留空，由教师填入本机可用的号码。
#: 写死一个未核实的全国热线是危险的 —— 打不通会延误求助。
CRISIS_CONTACT_PLACEHOLDER = "（请老师在此填入当地心理援助热线 / 校心理老师联系方式）"


@dataclass(frozen=True)
class Technique:
    name: str
    when: str
    how: str
    note: str = ""


@dataclass(frozen=True)
class Scenario:
    key: str
    title: str
    signs: str
    techniques: tuple[Technique, ...] = field(default_factory=tuple)


#: 按「我现在是什么状态」组织，而不是按心理学分类组织 ——
